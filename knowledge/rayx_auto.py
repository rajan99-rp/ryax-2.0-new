
from rayx_math_engine import solve_math
from rayx_knowledge import search_knowledge


def answer_question(
    question,
    model,
    config,
    generate_answer,
    find_memory_answer=None,
):
    """
    Route a question through:
    1. Local maths engine
    2. Knowledge base
    3. Existing conversation memory
    4. Local neural model

    No external AI API is used.
    """

    question = str(question).strip()

    if not question:
        return {
            "answer": "Please enter a question.",
            "source": "none",
            "verified": False,
            "details": "Empty question",
        }

    # 1. Solve supported mathematical expressions.
    math_result = solve_math(question)

    if math_result is not None:
        return {
            "answer": math_result,
            "source": "calculator",
            "verified": True,
            "details": "Calculated locally using the maths engine",
        }

    # 2. Search local subject knowledge.
    knowledge_result = search_knowledge(question)

    if knowledge_result is not None:
        return {
            "answer": knowledge_result["answer"],
            "source": "knowledge_base",
            "verified": knowledge_result.get("verified", False),
            "details": (
                f"Subject: {knowledge_result.get('subject', 'General')}; "
                f"Language: {knowledge_result.get('language', 'unknown')}; "
                f"Source: {knowledge_result.get('source', 'unspecified')}; "
                f"Match score: {knowledge_result.get('score', 0)}"
            ),
        }

    # 3. Search previously stored conversations.
    if find_memory_answer is not None:
        memory_result = find_memory_answer(question)

        if memory_result:
            return {
                "answer": memory_result["answer"],
                "source": "memory",
                "verified": False,
                "details": (
                    "Retrieved from stored conversation; "
                    "factual correctness is not guaranteed"
                ),
            }

    # 4. Fall back to the existing locally trained model.
    try:
        generated = generate_answer(model, config, question)
    except Exception as error:
        return {
            "answer": (
                "RayX could not generate an answer. "
                "Check the model and generation configuration."
            ),
            "source": "error",
            "verified": False,
            "details": f"Generation failed: {type(error).__name__}",
        }

    if not isinstance(generated, str) or not generated.strip():
        return {
            "answer": "RayX could not generate an answer for this question yet.",
            "source": "none",
            "verified": False,
            "details": "No usable answer generated",
        }

    return {
        "answer": generated.strip(),
        "source": "neural_model",
        "verified": False,
        "details": (
            "Generated by the local model; "
            "not independently verified"
        ),
    }


if __name__ == "__main__":
    print("RayX Hybrid router loaded successfully.")
    print("Math engine and knowledge base imports are available.")
